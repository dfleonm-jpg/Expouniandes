// Convierte literales de string exactos en el tipo general `string` de forma recursiva,
// así todas las traducciones son compatibles entre sí.
type Widen<T> = T extends string
  ? string
  : T extends readonly (infer U)[]
    ? readonly Widen<U>[]
    : { [K in keyof T]: Widen<T[K]> };

